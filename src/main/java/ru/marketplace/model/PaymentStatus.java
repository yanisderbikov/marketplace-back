package ru.marketplace.model;

/** Статус оплаты заказа через терминал Т-Банка магазина. */
public enum PaymentStatus {
    /** Заказ создан, платёж в Т-Банке инициирован, ждём подтверждения */
    AWAITING_PAYMENT,
    /** Т-Банк подтвердил оплату (CONFIRMED) — только такие заказы видит аналитика */
    PAID,
    /** Платёж отклонён, истёк или не создался */
    FAILED,
    /** Платёж отменён или возвращён */
    CANCELED
}
